package com.divyanshi;

public class Loops {
    public static void main(String[] args) {
        /*
        Syntax for for loops:
        for(initialization ; condition ; increment/decrement){
             body
          }
        */
        //Q. print numbers from 1 to 5
        for(int num =1;num<=5;num++ ){
            System.out.println(num);
        }
    }
}
